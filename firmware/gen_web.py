"""PlatformIO pre-build step: bundle tools/web into one gzipped page.

index.html gets analysis.js and the track library (tools/tracks/*.json)
inlined, so the page works offline on the box's Wi-Fi. Outputs:
  firmware/include/web_page.h   gzipped bytes served by the firmware
  tools/web/build/moto-metrik.html   same page, to open locally on a PC/phone
"""
import gzip
import json
from pathlib import Path

try:
    Import("env")  # noqa: F821  (PlatformIO)
    ROOT = Path(env["PROJECT_DIR"]).parent  # noqa: F821
except NameError:
    ROOT = Path(__file__).resolve().parent.parent

web = ROOT / "tools" / "web"
tracks = [json.loads(p.read_text()) for p in sorted((ROOT / "tools" / "tracks").glob("*.json"))]
for t in tracks:  # 7 decimals are ~1 cm: keep the page small
    t["centerline"] = [[round(a, 6), round(b, 6)] for a, b in t["centerline"]]
html = (web / "index.html").read_text()
html = html.replace("/*ANALYSIS_JS*/", (web / "analysis.js").read_text())
html = html.replace("/*TRACKS_JSON*/[]", json.dumps(tracks, separators=(",", ":")))

(web / "build").mkdir(exist_ok=True)
(web / "build" / "moto-metrik.html").write_text(html)

gz = gzip.compress(html.encode(), 9)
lines = [", ".join(f"0x{b:02x}" for b in gz[i:i + 20]) for i in range(0, len(gz), 20)]
header = ("// Generated by gen_web.py from tools/web - do not edit.\n#pragma once\n#include <Arduino.h>\n"
          f"static const size_t WEB_PAGE_GZ_LEN = {len(gz)};\n"
          "static const uint8_t WEB_PAGE_GZ[] PROGMEM = {\n  " + ",\n  ".join(lines) + "\n};\n")
out = ROOT / "firmware" / "include" / "web_page.h"
if not out.exists() or out.read_text() != header:
    out.write_text(header)
print(f"gen_web: page {len(html)} B, gzipped {len(gz)} B")
